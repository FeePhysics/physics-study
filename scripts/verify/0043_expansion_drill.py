"""ชุดฝึกบทที่ 28 — x = d/a คงที่ · λ_obs = (1+z) λ_emit"""
from sympy import Rational as R
ok = 0
def check(n, c):
    global ok; assert c, n; ok += 1; print("OK", n)
# ตารางในเนื้อบท
check("ตาราง: 6/1 = 6", R(6)/1 == 6); check("ตาราง: 2/(1/3) = 6", R(2)/R(1, 3) == 6)
# ข้อ 1
x = R(12)/1
check("ข้อ1 x=12", x == 12); check("ข้อ1 d(1/4)=3", R(1, 4)*x == 3); check("ข้อ1 3/(1/4)=12", R(3)/R(1, 4) == 12)
# ข้อ 2
x = R(2)/R(1, 5)
check("ข้อ2 x=10", x == 10); check("ข้อ2 d วันนี้=10", 1*x == 10); check("ข้อ2 d(1/2)=5", R(1, 2)*x == 5)
# ข้อ 3
check("ข้อ3 1+0=1", 1 + 0 == 1); check("ข้อ3 500", 1*500 == 500); check("ข้อ3 0*500=0", 0*500 == 0)
# ข้อ 4
check("ข้อ4 4*1216=4864", 4*1216 == 4864); check("ข้อ4 3*1216=3648 (คำตอบที่พลาด)", 3*1216 == 3648)
check("ข้อ4 3/2", 1 + R(1, 2) == R(3, 2)); check("ข้อ4 600", R(3, 2)*400 == 600)
# ข้อ 5
check("ข้อ5 ratio 5", R(2500, 500) == 5); check("ข้อ5 z=4", 5 - 1 == 4); check("ข้อ5 a=1/5", 1/R(5) == R(1, 5))
# ข้อ 6
a = 1/R(1 + 4)
check("ข้อ6 a=1/5", a == R(1, 5)); check("ข้อ6 d=4", a*20 == 4); check("ข้อ6 λ=1000", (1 + 4)*200 == 1000)
print(f"\n{ok}/{ok} ผ่าน")
