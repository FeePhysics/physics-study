"""บทที่ 32 · boost — เมทริกซ์ cosh/sinh (1+1) · spinor ยืด · Weyl สองครึ่ง (Tong (4.26), (4.31), (4.58)–(4.61), หน้า 92)"""
import sympy as sp
chi,t,x,th=sp.symbols('chi t x theta', real=True)
I=sp.I; s3=sp.Matrix([[1,0],[0,-1]]); E=sp.eye(2)
ok=0
def check(n,c):
    global ok; assert c,n; ok+=1; print("✅",n)
L=sp.Matrix([[sp.cosh(chi),-sp.sinh(chi)],[-sp.sinh(chi),sp.cosh(chi)]])
v=L*sp.Matrix([t,x])
check("t'²−x'² = t²−x²", sp.simplify(v[0]**2-v[1]**2-(t**2-x**2))==0)
check("det Λ = 1", sp.simplify(L.det())==1)
c=sp.ln(2)
check("cosh ln2 = 5/4", sp.simplify(sp.cosh(c).rewrite(sp.exp))==sp.Rational(5,4))
check("sinh ln2 = 3/4", sp.simplify(sp.sinh(c).rewrite(sp.exp))==sp.Rational(3,4))
check("v = tanh ln2 = 3/5", sp.simplify(sp.tanh(c).rewrite(sp.exp))==sp.Rational(3,5))
w=(L*sp.Matrix([1,0])).subs(chi,c).applyfunc(lambda e: sp.simplify(e.rewrite(sp.exp)))
check("(1,0) → (5/4, −3/4)", w==sp.Matrix([sp.Rational(5,4),-sp.Rational(3,4)]))
check("t'²−x'² = 1", w[0]**2-w[1]**2==1)
# spinor boost: e^{±χσ3/2}
B=lambda k:(k*chi*s3/2).exp()
check("e^{χσ3/2} = diag(e^{χ/2},e^{-χ/2})", sp.simplify(B(1)-sp.diag(sp.exp(chi/2),sp.exp(-chi/2)))==sp.zeros(2))
c4=sp.ln(4)
check("χ=ln4 ⇒ χ/2 = ln2", sp.simplify(c4/2-sp.ln(2))==0)
check("e^{χ/2}=2, e^{-χ/2}=1/2", (sp.simplify(sp.exp(c4/2)),sp.simplify(sp.exp(-c4/2)))==(2,sp.Rational(1,2)))
u=B(1).subs(chi,c4)*sp.Matrix([1,0]); u=u.applyfunc(sp.simplify)
check("u+ (1,0) → (2,0) · |.|² 1→4", u==sp.Matrix([2,0]) and (u.H*u)[0]==4)
check("boost ไม่ unitary", sp.simplify((B(1).H*B(1)).subs(chi,c4))!=E)
R=(I*th*s3/2).exp()
check("rotation unitary", sp.simplify(R.H*R)==E)
check("|e^{iθ/2}|² = 1", sp.simplify(sp.Abs(sp.exp(I*th/2))**2)==1)
um=(B(-1).subs(chi,c4)*sp.Matrix([1,0])).applyfunc(sp.simplify)
check("u− (1,0) → (1/2,0)", um==sp.Matrix([sp.Rational(1,2),0]))
check("rotation 2π: both blocks −1", sp.simplify(R.subs(th,2*sp.pi))==-E)
check("Dirac: 2+2 = 4 complex = 8 real", (2+2, 2*(2+2))==(4,8))
print(f"{ok}/{ok}")
